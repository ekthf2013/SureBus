export function cleanSubwayStationName(raw: string): string {
  if (!raw) return '';
  return raw
    .replace(/\s*\(.*?\)/g, '')
    .replace(/역\b|역$/g, '')
    .replace(/[\s\t\r\n]+/g, '')
    .trim();
}

