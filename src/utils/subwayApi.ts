/**
 * 역 이름과 노선을 기반으로 실제 공식 평일 운행 시간표(출발 분 단위 목록) 생성 및 반환
 */
export function generateDailySubwayTimetable(
  stationName: string,
  lineName: string = '지하철',
  directionHint: string = ''
): number[] {
  const cleanName = cleanSubwayStationName(stationName);

  // 1. 방향 키 정규화 및 탐색
  let dirKey = '';
  if (directionHint.includes('모란') || directionHint.includes('복정') || directionHint.includes('가락시장')) dirKey = '모란';
  else if (directionHint.includes('별내') || directionHint.includes('암사') || directionHint.includes('구리') || directionHint.includes('장자호수')) dirKey = '별내';
  else if (directionHint.includes('오금') || directionHint.includes('수서') || directionHint.includes('경찰병원')) dirKey = '오금';
  else if (directionHint.includes('대화') || directionHint.includes('구파발') || directionHint.includes('독립문') || directionHint.includes('화정')) dirKey = '대화';
  else if (directionHint.includes('광교') || directionHint.includes('수지') || directionHint.includes('정자') || directionHint.includes('미금')) dirKey = '광교';
  else if (directionHint.includes('강남') || directionHint.includes('신사') || directionHint.includes('양재')) dirKey = '강남';
  else if (directionHint.includes('수원') || directionHint.includes('인천') || directionHint.includes('기흥')) dirKey = '수원';
  else if (directionHint.includes('왕십리') || directionHint.includes('청량리') || directionHint.includes('선릉') || directionHint.includes('도곡')) dirKey = '왕십리';
  else if (directionHint.includes('내선') || directionHint.includes('잠실') || directionHint.includes('건대')) dirKey = '강남';
  else if (directionHint.includes('외선') || directionHint.includes('신도림') || directionHint.includes('홍대') || directionHint.includes('사당')) dirKey = '신도림';

  // 2. 하드코딩된 평일 시간표 키 정확 매칭
  if (dirKey) {
    const exactKey = `${cleanName}_${dirKey}`;
    if (WEEKDAY_SUBWAY_TIMETABLES[exactKey]) {
      const hourlyMap = WEEKDAY_SUBWAY_TIMETABLES[exactKey];
      const result: number[] = [];
      Object.entries(hourlyMap).forEach(([hourStr, mins]) => {
        const hour = Number(hourStr);
        mins.forEach(m => {
          const totalMins = (hour >= 24 ? (hour - 24) : hour) * 60 + m;
          result.push(hour >= 24 ? totalMins + 24 * 60 : totalMins);
        });
      });
      result.sort((a, b) => a - b);
      if (result.length > 0) return result;
    }
  }

  // 3. 역 이름으로 부분 일치 키 탐색
  for (const [key, hourlyMap] of Object.entries(WEEKDAY_SUBWAY_TIMETABLES)) {
    const [st, dir] = key.split('_');
    if (cleanName.includes(st) || st.includes(cleanName)) {
      if (!dirKey || !dir || dirKey === dir || dir.includes(dirKey) || dirKey.includes(dir)) {
        const result: number[] = [];
        Object.entries(hourlyMap).forEach(([hourStr, mins]) => {
          const hour = Number(hourStr);
          mins.forEach(m => {
            const totalMins = (hour >= 24 ? (hour - 24) : hour) * 60 + m;
            result.push(hour >= 24 ? totalMins + 24 * 60 : totalMins);
          });
        });
        result.sort((a, b) => a - b);
        if (result.length > 0) return result;
      }
    }
  }

  // 4. 수도권 노선망 그래프(SUBWAY_LINES_DATA) 기반 역별 물리 평일 시간표 계산
  const sched = getSubwayScheduleInfo(lineName);
  const matchedLineKey = Object.keys(SUBWAY_LINES_DATA).find(l => l.includes(sched.line) || sched.line.includes(l));
  const lineData = matchedLineKey ? SUBWAY_LINES_DATA[matchedLineKey] : undefined;

  let travelOffsetMins = 0;
  if (lineData) {
    const stIndex = lineData.stations.findIndex(st => {
      const c = cleanSubwayStationName(st);
      return cleanName.includes(c) || c.includes(cleanName);
    });

    if (stIndex !== -1) {
      const isReverse = directionHint.includes(cleanSubwayStationName(lineData.terminals[0]));
      const distFromOriginTerminal = isReverse
        ? (lineData.stations.length - 1 - stIndex)
        : stIndex;

      travelOffsetMins = Math.round(distFromOriginTerminal * lineData.timePerStation);
    }
  }

  const [firstH, firstM] = sched.firstTrain.split(':').map(Number);
  const [lastH, lastM] = sched.lastTrain.split(':').map(Number);

  const firstMins = firstH * 60 + firstM;
  const lastMins = lastH < 4 ? (lastH + 24) * 60 + lastM : lastH * 60 + lastM;

  const timetable: number[] = [];
  let curTerminalDept = firstMins;

  while (curTerminalDept <= lastMins) {
    const stationDeptTime = curTerminalDept + travelOffsetMins;
    timetable.push(stationDeptTime);

    const hourOfDay = Math.floor(curTerminalDept / 60) % 24;
    const isPeak = (hourOfDay >= 7 && hourOfDay <= 9) || (hourOfDay >= 18 && hourOfDay <= 20);
    const interval = isPeak ? sched.peakIntervalMinutes : sched.offPeakIntervalMinutes;
    
    curTerminalDept += Math.max(2, Math.round(interval));
  }

  timetable.sort((a, b) => a - b);
  return timetable;
}

export interface ScheduledDepartureMatch {
  scheduledDepartureMins: number; // 실제 탑승할 열차 출발 시각 (분)
  platformWaitMins: number; // 승강장 대기 시간 (분)
  departureTimeStr: string; // "07:44"
  isOperating: boolean; // 운행 중 여부
  firstTrain: string;
  lastTrain: string;
  upcomingDepartures: Array<{
    trainNo: string;
    departureTime: string;
    departureMins: number;
    waitMinutes: number;
    destination: string;
    status: string;
  }>;
}

/**
 * 승객이 승강장에 도착한 시각(readyMins)을 기준으로 실제 지하철 시간표에 맞는 다음 열차 및 대기시간 매칭
 */
export function matchScheduledSubwayDeparture(
  stationName: string,
  lineName: string = '지하철',
  readyMins: number,
  directionHint: string = ''
): ScheduledDepartureMatch {
  const sched = getSubwayScheduleInfo(lineName);
  const cleanName = cleanSubwayStationName(stationName);
  const timetable = generateDailySubwayTimetable(cleanName, sched.line, directionHint);
  const destination = directionHint ? directionHint.replace(/방면|행/g, '').trim() : '종점';

  // readyMins 이후에 출발하는 열차 목록 탐색
  const futureTrains = timetable.filter(t => t >= readyMins);

  if (futureTrains.length === 0) {
    // 막차 이후 심야 시간대: 익일 첫차로 안내
    const firstTrainMins = timetable[0] || (5 * 60 + 30);
    const nextDayFirstTrain = firstTrainMins + 24 * 60;
    const wait = nextDayFirstTrain - readyMins;
    const hour = Math.floor(firstTrainMins / 60) % 24;
    const min = firstTrainMins % 60;
    const timeStr = `${String(hour).padStart(2, '0')}:${String(min).padStart(2, '0')}`;

    return {
      scheduledDepartureMins: firstTrainMins,
      platformWaitMins: wait,
      departureTimeStr: timeStr,
      isOperating: false,
      firstTrain: sched.firstTrain,
      lastTrain: sched.lastTrain,
      upcomingDepartures: [
        {
          trainNo: '첫차',
          departureTime: sched.firstTrain,
          departureMins: firstTrainMins,
          waitMinutes: wait,
          destination,
          status: '운행 마감 (익일 첫차 대기)'
        }
      ]
    };
  }

  const nextDepartureMins = futureTrains[0];
  const waitMins = Math.max(0, nextDepartureMins - readyMins);
  const hour = Math.floor(nextDepartureMins / 60) % 24;
  const min = nextDepartureMins % 60;
  const departureTimeStr = `${String(hour).padStart(2, '0')}:${String(min).padStart(2, '0')}`;

  const upcomingDepartures = futureTrains.slice(0, 3).map((depMins, idx) => {
    const h = Math.floor(depMins / 60) % 24;
    const m = depMins % 60;
    const tStr = `${String(h).padStart(2, '0')}:${String(m).padStart(2, '0')}`;
    const wait = depMins - readyMins;

    let status = '';
    if (wait === 0) status = '당역 진입';
    else if (wait <= 2) status = '전역 출발';
    else status = `${Math.min(idx + 1, 3)}개역 전`;

    return {
      trainNo: `${h}${String(m).padStart(2, '0')}${idx + 1}`,
      departureTime: tStr,
      departureMins: depMins,
      waitMinutes: wait,
      destination,
      status
    };
  });

  return {
    scheduledDepartureMins: nextDepartureMins,
    platformWaitMins: waitMins,
    departureTimeStr,
    isOperating: true,
    firstTrain: sched.firstTrain,
    lastTrain: sched.lastTrain,
    upcomingDepartures
  };
}

/**
 * 특정 목표 도착 시각 이전까지 도착 가능한 가장 늦은 지하철 출발 시각 조회
 */
export function findLatestScheduledDepartureBefore(
  stationName: string,
  lineName: string,
  latestDepartureMins: number,
  directionHint: string = ''
): number {
  const cleanName = cleanSubwayStationName(stationName);
  const timetable = generateDailySubwayTimetable(cleanName, lineName, directionHint);
  const validTrains = timetable.filter(t => t <= latestDepartureMins);
  if (validTrains.length > 0) {
    return validTrains[validTrains.length - 1];
  }
  return latestDepartureMins;
}

/**
 * 중복 열차 도착 정보 제거 (Deduplication)
 */
export function deduplicateSubwayArrivals(list: RealtimeArrival[]): RealtimeArrival[] {
  const seen = new Set<string>();
  const result: RealtimeArrival[] = [];

  for (const item of list) {
    const roundedMins = Math.round((Number(item.barvlDt) || 0) / 60);
    const key = `${item.subwayId}_${item.trainLineNm}_${item.updnLine}_${item.bstatnNm}_${item.arvlMsg2}_${roundedMins}`;

    if (!seen.has(key)) {
      seen.add(key);
      result.push(item);
    }
  }

  return result;
}

/**
 * 실시간 배차 간격 및 현재 시각 기반의 동적 도착 정보 생성기
 * (공공 API 일일 쿼터 초과 시에도 사용자가 항상 실시간 도착 및 다음 열차 현황을 확인할 수 있도록 보장)
 */
export function generateTimetableLiveArrivals(
  stationName: string,
  lineNameHint: string = '지하철',
  directionHint: string = ''
): RealtimeArrival[] {
  const cleanName = cleanSubwayStationName(stationName);
  const sched = getSubwayScheduleInfo(lineNameHint);

  const now = new Date();
  const currentHour = now.getHours();
  const currentMinute = now.getMinutes();
  const currentSecond = now.getSeconds();
  const nowMins = currentHour * 60 + currentMinute;

  // 실제 표준 시간표 매칭
  const match = matchScheduledSubwayDeparture(cleanName, sched.line, nowMins, directionHint);
  const subwayId = Object.keys(SUBWAY_LINE_MAP).find(id => SUBWAY_LINE_MAP[id].name === sched.line) || '1008';

  // 종착역/방면 결정
  let destination = directionHint ? directionHint.replace(/방면|행/g, '').trim() : '';
  const lineData = SUBWAY_LINES_DATA[sched.line];
  if (lineData) {
    if (!destination || destination === '종점') {
      destination = cleanSubwayStationName(lineData.terminals[1]);
    } else {
      const stIdx = lineData.stations.findIndex(s => cleanSubwayStationName(s).includes(cleanName) || cleanName.includes(cleanSubwayStationName(s)));
      const dirIdx = lineData.stations.findIndex(s => cleanSubwayStationName(s).includes(destination) || destination.includes(cleanSubwayStationName(s)));
      if (stIdx !== -1 && dirIdx !== -1) {
        if (dirIdx < stIdx) {
          destination = cleanSubwayStationName(lineData.terminals[0]);
        } else {
          destination = cleanSubwayStationName(lineData.terminals[1]);
        }
      }
    }
  }
  if (!destination) destination = '종점';

  const arrivals: RealtimeArrival[] = match.upcomingDepartures.map((train) => {
    // 잔여 초 계산
    const remainSecs = Math.max(15, (train.departureMins - nowMins) * 60 - currentSecond);
    const remainMins = Math.floor(remainSecs / 60);
    const remainSecsRemainder = remainSecs % 60;

    let msg = '';
    if (remainSecs <= 45) {
      msg = '당역 진입 (곧 도착)';
    } else if (remainSecs <= 90) {
      msg = '전역 도착 (약 1분 후)';
    } else {
      msg = `${remainMins}분 ${remainSecsRemainder > 0 ? `${remainSecsRemainder}초 ` : ''}후 (${train.status})`;
    }

    return {
      subwayId,
      subwayName: sched.line,
      updnLine: '하행',
      trainLineNm: `${destination}행`,
      statnNm: cleanName,
      btrainSttus: '일반',
      barvlDt: String(remainSecs),
      btrainNo: train.trainNo,
      bstatnNm: destination,
      arvlMsg2: msg,
      arvlMsg3: cleanName,
      arvlCd: remainSecs <= 45 ? '0' : '99',
      recptnDt: now.toLocaleTimeString('ko-KR', { hour12: false }),
      isFallback: true
    };
  });

  return arrivals;
}

/**
 * 역 이름으로 실시간 도착정보 조회
 * @param rawStationName (예: "장자호수공원역 (8호선)", "장자호수공원", "잠실역")
 * @param lineHint 호선 힌트 (예: "3호선", "8호선", "신분당선")
 * @param directionHint 방면 힌트 (예: "오금행", "모란행", "광교행")
 */
export async function fetchRealtimeSubwayArrival(
  rawStationName: string,
  lineHint: string = '',
  directionHint: string = ''
): Promise<RealtimeArrival[]> {
  const apiKey = (typeof import.meta !== 'undefined' && import.meta.env?.VITE_SEOUL_METRO_API_KEY) || '626d564950656b743337597876534a';
  const stationClean = cleanSubwayStationName(rawStationName);
  if (!stationClean) return [];

  const url = `/api/subway/${apiKey}/json/realtimeStationArrival/0/10/${encodeURIComponent(stationClean)}`;

  try {
    let res = await fetch(url);
    if (!res.ok) {
      res = await fetch(`http://swopenAPI.seoul.go.kr/api/subway/${apiKey}/json/realtimeStationArrival/0/10/${encodeURIComponent(stationClean)}`);
    }

    if (res.ok) {
      const data = await res.json();

      if (data.realtimeArrivalList && Array.isArray(data.realtimeArrivalList) && data.realtimeArrivalList.length > 0) {
        const rawList = data.realtimeArrivalList.map((item: any) => {
          const lineInfo = SUBWAY_LINE_MAP[item.subwayId];
          return {
            subwayId: item.subwayId || '',
            subwayName: lineInfo ? lineInfo.name : '지하철',
            updnLine: item.updnLine || '',
            trainLineNm: item.trainLineNm || '',
            statnNm: item.statnNm || stationClean,
            btrainSttus: item.btrainSttus || '일반',
            barvlDt: item.barvlDt || '0',
            btrainNo: item.btrainNo || '',
            bstatnNm: item.bstatnNm || '',
            arvlMsg2: item.arvlMsg2 || '',
            arvlMsg3: item.arvlMsg3 || '',
            arvlCd: item.arvlCd || '',
            recptnDt: item.recptnDt || '',
            isFallback: false
          };
        });

        const deduped = deduplicateSubwayArrivals(rawList);
        if (deduped.length > 0) {
          return deduped;
        }
      }
    }
  } catch (error) {
    console.warn(`[SubwayAPI] API 응답 제한 또는 오류 (${stationClean}) ➔ 실시간 시각표 엔진 가동:`, error);
  }

  // API 쿼터 초과 또는 비지원 역(신분당선 일부 역 등)인 경우 시각표 & 배차 엔진으로 실시간 생성
  return generateTimetableLiveArrivals(stationClean, lineHint, directionHint);
}
